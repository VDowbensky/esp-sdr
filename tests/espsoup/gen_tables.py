"""Generate the constant tables of main/families/c5_c6_c61/demod_tab.h (bit-exact on host and device).

Usage: python gen_tables.py [output]   (default: the header in the source tree)"""
import math
import sys
from pathlib import Path
out = []
out.append("/* SPDX-License-Identifier: GPL-3.0-or-later\n * Generated by tests/espsoup/gen_tables.py - do not edit. */")
out.append("#pragma once")
out.append("#include <stdint.h>")
# atan2 phase of a 6-bit/6-bit quantised I/Q cell: idx = (i6 & 63) | ((q6 & 63) << 6), cell centre (v + 0.5)
tab = []
for idx in range(4096):
    i6 = idx & 63; q6 = (idx >> 6) & 63
    if i6 >= 32: i6 -= 64
    if q6 >= 32: q6 -= 64
    a = math.atan2(q6 + 0.5, i6 + 0.5)
    tab.append(int(math.floor(a * 256 / (2 * math.pi) + 0.5)) & 255)
out.append("/* phase (2*pi/256 units) of the quantisation cell centre (i + 0.5, q + 0.5) */")
out.append("static const uint8_t vf_atan_tab[4096] = {")
for r in range(0, 4096, 32):
    out.append("    " + ",".join(str(x) for x in tab[r:r + 32]) + ",")
out.append("};")
# PARLIO bytes (parlio_cap.h): low nibble I, high nibble Q, signed 4-bit, cell centre (v + 0.5)
pt = []
for idx in range(256):
    i4 = idx & 15; q4 = idx >> 4
    if i4 >= 8: i4 -= 16
    if q4 >= 8: q4 -= 16
    pt.append(int(math.floor(math.atan2(q4 + 0.5, i4 + 0.5) * 256 / (2 * math.pi) + 0.5)) & 255)
out.append("/* phase (2*pi/256 units) of a PARLIO byte (I = low nibble, Q = high nibble, signed, cell centre v + 0.5) */")
out.append("static const uint8_t vf_ptab[256] = {")
for r in range(0, 256, 32):
    out.append("    " + ",".join(str(x) for x in pt[r:r + 32]) + ",")
out.append("};")
# 30103 * log2(1 + j/64), j = 0..64 (for 100*10*log10)
lt = [int(math.floor(30103 * math.log2(1 + j / 64) + 0.5)) for j in range(65)]
out.append("static const int16_t dm_lt[65] = {" + ",".join(map(str, lt)) + "};")
dst = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "main/families/c5_c6_c61/demod_tab.h"
dst.write_text("\n".join(out) + "\n", newline="\n")
print("ok", sum(tab))
